export async function initI18n(language: 'uk' | 'ru' | 'en' = 'uk') {
  await i18next.init({
    lng: language,
    fallbackLng: 'uk',
    resources,
    interpolation: { escapeValue: false },
  });
  return i18next;
}

export function t(key: string, options?: Record<string, unknown>): string {
  return i18next.t(key, options);
}

export function changeLanguage(lang: 'uk' | 'ru' | 'en') {
  return i18next.changeLanguage(lang);
}